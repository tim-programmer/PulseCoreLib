/*
 * gen_tables - emits src/core/pcl_tables.c.
 *
 *     gen_tables > src/core/pcl_tables.c
 *
 * The output is checked in, because C99 cannot evaluate sin/exp2 at compile time.
 * tests/test_tables.c compares the checked-in tables against libm, so a stale file
 * fails the build.
 *
 * Tables (all 256 segments plus one guard entry for interpolation):
 *   pcl_sine_quarter_tab  sin(pi/2 * i/256), one entry type per sample type
 *   pcl_exp2_tab          (2^(i/256) - 1) * 2^16 as uint16_t; the last entry is 2^16 and
 *                         is saturated to 65535 (error: one 16-bit LSB in the last segment)
 *   pcl_log2_tab          log2(1 + i/256) * 2^16 as uint16_t; the last entry is 2^16, saturated
 *   pcl_tanh_tab          tanh(i/64) for i = 0..384 (x in [0, 6]), one entry type per sample type
 */
#include <math.h>
#include <stdio.h>

#define SEGMENTS 256
#define TANH_SEGMENTS 384
#define TANH_STEPS_PER_UNIT 64
#define PER_LINE 8

static const double pi = 3.14159265358979323846;

static void emit_int(const char *decl, const long long *v, int segments)
{
    int i;
    printf("%s\n{", decl);
    for (i = 0; i <= segments; i++)
        printf("%s%*lld,", (i % PER_LINE == 0) ? "\n    " : " ", 11, v[i]);
    printf("\n};\n\n");
}

int main(void)
{
    long long q15[SEGMENTS + 1], q31[SEGMENTS + 1], exp2m[SEGMENTS + 1], log2m[SEGMENTS + 1];
    long long th15[TANH_SEGMENTS + 1], th31[TANH_SEGMENTS + 1];
    int       i;

    for (i = 0; i <= SEGMENTS; i++)
    {
        const double s = sin(pi / 2.0 * (double)i / (double)SEGMENTS);
        long long    e = llround((exp2((double)i / (double)SEGMENTS) - 1.0) * 65536.0);
        q15[i] = llround(s * 32767.0);
        q31[i] = llround(s * 2147483647.0);
        exp2m[i] = e > 65535 ? 65535 : e;
        e = llround(log2(1.0 + (double)i / (double)SEGMENTS) * 65536.0);
        log2m[i] = e > 65535 ? 65535 : e;
    }
    for (i = 0; i <= TANH_SEGMENTS; i++)
    {
        const double t = tanh((double)i / (double)TANH_STEPS_PER_UNIT);
        th15[i] = llround(t * 32767.0);
        th31[i] = llround(t * 2147483647.0);
    }

    printf("/* Generated by tools/gen_tables.c - do not edit. */\n");
    printf("#include \"core/pcl_tables.h\"\n\n");

    printf("#if PCL_SAMPLE_TYPE == PCL_FLOAT\n");
    printf("const pcl_sample_t pcl_sine_quarter_tab[PCL_QUARTER_SINE_SEGMENTS + 1u] =\n{");
    for (i = 0; i <= SEGMENTS; i++)
        printf("%s%.9ef,", (i % 4 == 0) ? "\n    " : " ",
            sin(pi / 2.0 * (double)i / (double)SEGMENTS));
    printf("\n};\n");
    printf("#elif PCL_SAMPLE_TYPE == PCL_Q15\n");
    emit_int(
        "const pcl_sample_t pcl_sine_quarter_tab[PCL_QUARTER_SINE_SEGMENTS + 1u] =", q15, SEGMENTS);
    printf("#else\n");
    emit_int(
        "const pcl_sample_t pcl_sine_quarter_tab[PCL_QUARTER_SINE_SEGMENTS + 1u] =", q31, SEGMENTS);
    printf("#endif\n\n");

    emit_int("const uint16_t pcl_exp2_tab[PCL_EXP2_SEGMENTS + 1u] =", exp2m, SEGMENTS);
    emit_int("const uint16_t pcl_log2_tab[PCL_LOG2_SEGMENTS + 1u] =", log2m, SEGMENTS);

    printf("#if PCL_SAMPLE_TYPE == PCL_FLOAT\n");
    printf("const pcl_sample_t pcl_tanh_tab[PCL_TANH_SEGMENTS + 1u] =\n{");
    for (i = 0; i <= TANH_SEGMENTS; i++)
        printf("%s%.9ef,", (i % 4 == 0) ? "\n    " : " ",
            tanh((double)i / (double)TANH_STEPS_PER_UNIT));
    printf("\n};\n");
    printf("#elif PCL_SAMPLE_TYPE == PCL_Q15\n");
    emit_int("const pcl_sample_t pcl_tanh_tab[PCL_TANH_SEGMENTS + 1u] =", th15, TANH_SEGMENTS);
    printf("#else\n");
    emit_int("const pcl_sample_t pcl_tanh_tab[PCL_TANH_SEGMENTS + 1u] =", th31, TANH_SEGMENTS);
    printf("#endif\n");
    return 0;
}
